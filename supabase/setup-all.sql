-- 2) New tables
create table if not exists public.settings (
  key   text primary key,
  value text
);

create table if not exists public.testimonials (
  id         bigint generated by default as identity primary key,
  name       text not null,
  quote      text not null,
  visible    boolean not null default true,
  sort_order int not null default 100
);

create table if not exists public.faqs (
  id         bigint generated by default as identity primary key,
  question   text not null,
  answer     text not null,
  visible    boolean not null default true,
  sort_order int not null default 100
);

create table if not exists public.locations (
  id         bigint generated by default as identity primary key,
  name       text not null,
  page       text,                 -- e.g. 'lagos.html' (optional link)
  trips      text,                 -- e.g. '5010+ Trips'
  legacy_img text,                 -- photo that ships with the website
  image_path text,                 -- photo uploaded from the dashboard
  visible    boolean not null default true,
  sort_order int not null default 100
);

create table if not exists public.enquiries (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  source      text not null default 'booking-form',
  location    text,
  vehicle     text,
  service     text,
  pickup      date,
  return_date date,
  car_id      bigint,
  car_name    text,
  message     text,
  status      text not null default 'new',
  note        text,
  constraint enquiries_status_ok  check (status in ('new','followed_up','booked','not_interested')),
  constraint enquiries_source_ok  check (source in ('booking-form','car')),
  constraint enquiries_len_ok     check (char_length(coalesce(message,'')) <= 1500
                                     and char_length(coalesce(location,'')) <= 80
                                     and char_length(coalesce(vehicle,'')) <= 120
                                     and char_length(coalesce(service,'')) <= 60
                                     and char_length(coalesce(car_name,'')) <= 160
                                     and char_length(coalesce(note,'')) <= 2000)
);
create index if not exists enquiries_created_idx on public.enquiries (created_at desc);

