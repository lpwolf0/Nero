-- 1) Extra fields on cars: features list, gallery photos, self-drive price
alter table public.cars add column if not exists features text[] not null default '{}';
alter table public.cars add column if not exists gallery  text[] not null default '{}';
alter table public.cars add column if not exists price_self_drive numeric;

-- 2) New tables
create table if not exists public.settings (
  key   text primary key,
  value text
);

create table if not exists public.testimonials (
  id         bigint generated by default as identity primary key,
  name       text not null,
  quote      text not null,
  visible    boolean not null default true,
  sort_order int not null default 100
);

create table if not exists public.faqs (
  id         bigint generated by default as identity primary key,
  question   text not null,
  answer     text not null,
  visible    boolean not null default true,
  sort_order int not null default 100
);

create table if not exists public.locations (
  id         bigint generated by default as identity primary key,
  name       text not null,
  page       text,                 -- e.g. 'lagos.html' (optional link)
  trips      text,                 -- e.g. '5010+ Trips'
  legacy_img text,                 -- photo that ships with the website
  image_path text,                 -- photo uploaded from the dashboard
  visible    boolean not null default true,
  sort_order int not null default 100
);

create table if not exists public.enquiries (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  source      text not null default 'booking-form',
  location    text,
  vehicle     text,
  service     text,
  pickup      date,
  return_date date,
  car_id      bigint,
  car_name    text,
  message     text,
  status      text not null default 'new',
  note        text,
  constraint enquiries_status_ok  check (status in ('new','followed_up','booked','not_interested')),
  constraint enquiries_source_ok  check (source in ('booking-form','car')),
  constraint enquiries_len_ok     check (char_length(coalesce(message,'')) <= 1500
                                     and char_length(coalesce(location,'')) <= 80
                                     and char_length(coalesce(vehicle,'')) <= 120
                                     and char_length(coalesce(service,'')) <= 60
                                     and char_length(coalesce(car_name,'')) <= 160
                                     and char_length(coalesce(note,'')) <= 2000)
);
create index if not exists enquiries_created_idx on public.enquiries (created_at desc);

-- 3) Security
alter table public.settings     enable row level security;
alter table public.testimonials enable row level security;
alter table public.faqs         enable row level security;
alter table public.locations    enable row level security;
alter table public.enquiries    enable row level security;

-- settings: everyone reads (they are public site details), only the admin writes
drop policy if exists "public read settings" on public.settings;
create policy "public read settings" on public.settings for select to anon, authenticated using (true);
drop policy if exists "admin manage settings" on public.settings;
create policy "admin manage settings" on public.settings for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- testimonials / faqs / locations: everyone reads visible rows, only the admin writes
drop policy if exists "public read testimonials" on public.testimonials;
create policy "public read testimonials" on public.testimonials for select to anon, authenticated using (visible = true or public.is_admin());
drop policy if exists "admin manage testimonials" on public.testimonials;
create policy "admin manage testimonials" on public.testimonials for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "public read faqs" on public.faqs;
create policy "public read faqs" on public.faqs for select to anon, authenticated using (visible = true or public.is_admin());
drop policy if exists "admin manage faqs" on public.faqs;
create policy "admin manage faqs" on public.faqs for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "public read locations" on public.locations;
create policy "public read locations" on public.locations for select to anon, authenticated using (visible = true or public.is_admin());
drop policy if exists "admin manage locations" on public.locations;
create policy "admin manage locations" on public.locations for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- enquiries: website visitors may only ADD a new one; only the admin can read, edit or delete
drop policy if exists "visitors add enquiries" on public.enquiries;
create policy "visitors add enquiries" on public.enquiries for insert to anon, authenticated
  with check (status = 'new' and note is null);
drop policy if exists "admin read enquiries" on public.enquiries;
create policy "admin read enquiries" on public.enquiries for select to authenticated using (public.is_admin());
drop policy if exists "admin update enquiries" on public.enquiries;
create policy "admin update enquiries" on public.enquiries for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "admin delete enquiries" on public.enquiries;
create policy "admin delete enquiries" on public.enquiries for delete to authenticated using (public.is_admin());

grant select on public.settings, public.testimonials, public.faqs, public.locations to anon;
grant select, insert, update, delete on public.settings, public.testimonials, public.faqs, public.locations to authenticated;
grant insert on public.enquiries to anon;
grant select, insert, update, delete on public.enquiries to authenticated;

-- 4) Photo storage: make sure the admin can read, replace and delete photos
drop policy if exists "admin read car images" on storage.objects;
create policy "admin read car images" on storage.objects for select to authenticated using (bucket_id = 'car-images' and public.is_admin());
drop policy if exists "admin update car images" on storage.objects;
create policy "admin update car images" on storage.objects for update to authenticated
  using (bucket_id = 'car-images' and public.is_admin()) with check (bucket_id = 'car-images' and public.is_admin());

